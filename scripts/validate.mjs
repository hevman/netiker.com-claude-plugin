import assert from 'node:assert/strict';
import {readFile,access} from 'node:fs/promises';
const root=new URL('../',import.meta.url);
const read=async path=>JSON.parse(await readFile(new URL(path,root),'utf8'));
const catalog=await read('.claude-plugin/marketplace.json');
const manifest=await read('plugins/netiker/.claude-plugin/plugin.json');
const config=await read('plugins/netiker/.mcp.json');
assert.equal(catalog.name,'netiker');
assert.equal(catalog.plugins.length,1);
assert.equal(catalog.plugins[0].source,'./plugins/netiker');
assert.equal(catalog.plugins[0].name,manifest.name);
assert.match(manifest.version,/^\d+\.\d+\.\d+$/);
assert.equal(config.mcpServers.netiker.type,'http');
assert.equal(config.mcpServers.netiker.url,'https://app.netiker.com/mcp');
assert.equal(config.mcpServers.netiker.oauth.scopes,'reports:read runs:read');
assert.equal(config.mcpServers.netiker.headers,undefined);
assert.equal(config.mcpServers.netiker.command,undefined);
await access(new URL('plugins/netiker/assets/icon.png',root));
const skill=await readFile(new URL('plugins/netiker/skills/netiker/SKILL.md',root),'utf8');
assert.match(skill,/name: netiker/);
assert.match(skill,/read_report_rows/);
assert.ok(!JSON.stringify(config).includes('com.openai'));
console.log(`Netiker Claude plugin ${manifest.version}: marketplace, manifest, HTTP/OAuth and analysis skill validated.`);
